#!/usr/bin/env python3
"""Generate Codex subagents (.codex/agents/*.toml) from the Claude Code ones (.claude/agents/*.md).

Single source of truth: .claude/agents/*.md. Model policy: a large model orchestrates, subagents run small
(Claude Code: haiku; Codex: CODEX_SUBAGENT_MODEL). Codex agents are read-only.
  python3 tools/sync_codex_agents.py          # write files
  python3 tools/sync_codex_agents.py --check  # exit 1 if out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, DST = os.path.join(ROOT, ".claude", "agents"), os.path.join(ROOT, ".codex", "agents")
CODEX_SUBAGENT_MODEL = "gpt-6-luna"
NOTE = ("You run as a Codex subagent in a read-only sandbox. Use the web search or browsing tools available "
        "to you for public pages; if none is available, record the items as unavailable instead of guessing.\n\n")


def render(md_path):
    text = open(md_path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    fm = dict(line.split(":", 1) for line in m.group(1).splitlines())
    body = NOTE + m.group(2).strip() + "\n"
    if "'''" in body:
        raise SystemExit("%s: body cannot contain ''' (TOML literal string)" % md_path)
    desc = fm["description"].strip().replace("\\", "\\\\").replace('"', '\\"')
    return ('# Generated by tools/sync_codex_agents.py from .claude/agents/%s - edit the source, not this file.\n'
            'name = "%s"\ndescription = "%s"\nmodel = "%s"\nsandbox_mode = "read-only"\n\n'
            "developer_instructions = '''\n%s'''\n"
            % (os.path.basename(md_path), fm["name"].strip(), desc, CODEX_SUBAGENT_MODEL, body))


def main():
    check = "--check" in sys.argv
    os.makedirs(DST, exist_ok=True)
    stale = []
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".md"):
            continue
        out = os.path.join(DST, f[:-3] + ".toml")
        data = render(os.path.join(SRC, f))
        current = open(out, encoding="utf-8").read() if os.path.exists(out) else None
        if current != data:
            stale.append(out)
            if not check:
                with open(out, "w", encoding="utf-8") as fh:
                    fh.write(data)
    print(("stale: %s" if check else "written: %s") % [os.path.relpath(p, ROOT) for p in stale])
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
